export class CarDatabase {
  constructor() { this._cars = new Map(); }

  async load() {
    for (const car of CAR_ROSTER) this._cars.set(car.id, car);
    console.log(`[CarDatabase] Loaded ${this._cars.size} cars ✓`);
  }

  get(id)     { return this._cars.get(id) || null; }
  getAll()    { return Array.from(this._cars.values()); }
  getByClass(cls) { return this.getAll().filter(c => c.class === cls); }

  getStarterCars() { return this.getAll().filter(c => c.tier === 1).slice(0, 3); }
}

